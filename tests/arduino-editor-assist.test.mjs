import assert from 'node:assert/strict';
import { codeKeyEdit, formatIndentation, scanCpp, toggleLineComment, indentSelection } from '../assets/js/arduino-source-editor.mjs';
import { parseCompilerDiagnostics, describeDiagnostic, applyDiagnosticFix } from '../assets/js/arduino-diagnostics.mjs';

const key = (text, position, name, extra = {}) => codeKeyEdit(text, position, position, { key: name, ...extra });
assert.deepEqual(key('void loop() {}', 13, 'Enter'), { text:'void loop() {\n  \n}',start:16,end:16 });
assert.deepEqual(key('  if (true) {',13,'Enter'),{text:'  if (true) {\n    ',start:18,end:18});
assert.deepEqual(key('digitalWrite',12,'('),{text:'digitalWrite()',start:13,end:13});
assert.deepEqual(key('()',1,')'),{text:'()',start:2,end:2});
assert.deepEqual(key('()',1,'Backspace'),{text:'',start:0,end:0});
assert.equal(key('// comment ',11,'('),null,'No paired brackets inside comments');
assert.equal(key('"abc',4,'('),null,'No paired brackets inside strings');
assert.equal(key('/* comment ',11,'{'),null);
assert.equal(key('x',1,'(',{isComposing:true}),null);
assert.equal(key('x',1,'(',{ctrlKey:true}),null);
assert.equal(indentSelection('\nabc',0,0).text,'  \nabc','Indent at the beginning of a blank first line');
assert.equal(codeKeyEdit('value',0,5,{key:'('}).text,'(value)');
assert.equal(toggleLineComment('  first();\n  second();',0,23).text,'  // first();\n  // second();');
assert.equal(toggleLineComment('  // first();\n  // second();',0,28).text,'  first();\n  second();');
assert.equal(formatIndentation('void loop() {\ndigitalWrite(5, HIGH);\nif (true) {\ndelay(1);\n}\n}').text,'void loop() {\n  digitalWrite(5, HIGH);\n  if (true) {\n    delay(1);\n  }\n}');
assert.equal(formatIndentation('void loop(){\nSerial.println("} {"); // {\ndelay(1);\n}').text,'void loop(){\n  Serial.println("} {"); // {\n  delay(1);\n}');
const raw='void loop(){\nconst char* s=R"tag(\n   { literal content }\n   )tag";\ndelay(1);\n}';
assert.ok(formatIndentation(raw).text.includes('\n   { literal content }\n   )tag";'),'Raw string bytes are preserved');
assert.equal(key('auto s=R"(  literal','auto s=R"(  literal'.length,'Enter').text,'auto s=R"(  literal\n','Enter inside a raw literal adds no automatic whitespace');
assert.equal(formatIndentation('void loop(){\n/* comment\n*/ if (true) {\ndelay(1);\n}\n}').text,'void loop(){\n  /* comment\n*/ if (true) {\n    delay(1);\n  }\n}','Code after a multiline comment still affects indentation depth');
const macro='#define EXAMPLE(x) \\\n  { x; }\nvoid loop(){\ndelay(1);\n}';
assert.ok(formatIndentation(macro).text.startsWith('#define EXAMPLE(x) \\\n  { x; }\n'),'Multiline macro indentation is preserved');
assert.equal(scanCpp('"} {" // (\n{ /* } */ }').masked.trim(),'{         }');
const nonAscii='// český komentář 😀\nvoid loop(){\ndelay(1);\n}';
assert.ok(formatIndentation(nonAscii).text.startsWith('// český komentář 😀\n'));
const formatted=formatIndentation('void loop(){\ndelay(1);\n}',13,18);
assert.equal(formatted.text.slice(formatted.start,formatted.end),'delay','Selection tracks indentation changes');

const source='void setup() {}\nvoid loop() {\n  digitalWrite(LED_GREEN, LOW;\n}';
const column=source.split('\n')[2].indexOf(';')+1;
const error=`[cc1plus] shieldio.ino:3:${column}: error: expected ')' before ';' token`;
const problems=parseCompilerDiagnostics(error+'\n'+error,source);
assert.equal(problems.length,1,'Duplicate compiler errors are collapsed');
assert.equal(problems[0].kind,'closingParen');assert.equal(problems[0].line,3);
assert.ok(problems[0].inSketch);assert.ok(problems[0].fix);
const fix=applyDiagnosticFix(source,source,problems[0].fix);
assert.ok(fix.text.includes('digitalWrite(LED_GREEN, LOW);'));
assert.equal(applyDiagnosticFix(source+' ',source,problems[0].fix),null,'Never apply a stale fix');
assert.equal(describeDiagnostic(problems[0]).title,'Chybí uzavírací závorka ).');
assert.match(describeDiagnostic(problems[0],'en').title,/parenthesis/);
const uncertain=parseCompilerDiagnostics("shieldio.ino:3:3: error: expected ')' before ';' token",source)[0];
assert.equal(uncertain.fix,undefined,'Only offer a patch at the precise semicolon');
const nested='void loop(){\n  f(g(1;\n}';
assert.equal(parseCompilerDiagnostics("shieldio.ino:2:8: error: expected ')' before ';' token",nested)[0].fix,undefined);
const library=parseCompilerDiagnostics('Custom.h:12:5: error: invalid conversion from int to char*',source)[0];
assert.equal(library.inSketch,false,'Library errors must not select a sketch line');
assert.equal(library.kind,'arguments');
assert.equal(parseCompilerDiagnostics('shieldio.ino:1:1: warning: unused variable',source).length,0);
assert.equal(parseCompilerDiagnostics('shieldio.ino:1:1: note: suggested alternative',source).length,0);
assert.equal(parseCompilerDiagnostics("shieldio.ino:1:1: error: 'digitalwrite' was not declared in this scope",source)[0].symbol,'digitalwrite');
assert.equal(parseCompilerDiagnostics('shieldio.ino:1:1: fatal error: Missing.h: No such file or directory',source)[0].kind,'library');
console.log('Editor assistance: indentation, comments, pairing, literal preservation, diagnostic parsing, source locations and guarded fixes passed.');
