const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '../learn/worker.js'), 'utf8');
const context = vm.createContext({});
context.URLSearchParams = URLSearchParams;
vm.runInContext(source.slice(source.indexOf('function parseAbsenceNoteDialog('), source.indexOf('async function inspectAbsenceNoteForm(')), context);
const profile = html => JSON.parse(JSON.stringify(context.absenceNoteFormProfile(html)));
assert.equal(profile('<textarea></textarea> datepicker periodfrom').status, 'recognized');
assert.equal(profile('<html>Login</html>').status, 'unknown');
assert.equal(profile('datepicker').status, 'unknown');
const sensitive = profile('<textarea></textarea> datepicker studentid="PRIVATE_ID" gsh="SECRET" password="PASSWORD" ASC_action("save", {})');
assert.equal(sensitive.directSending, false);
assert.equal(sensitive.hasJscAction, true);
assert.ok(!JSON.stringify(sensitive).match(/PRIVATE_ID|SECRET|PASSWORD|save/));
assert.deepEqual(sensitive.fields, ['reason', 'dates']);
assert.deepEqual(sensitive.parameterHints, ['studentid']);
console.log('Profil formuláře: rozpoznání, neznámá odpověď a ochrana citlivých hodnot OK');
const fixture = `gi42._gclass = "OspravedlnenkaDlg";gi42.myphpfile = "/gcall";gi42._gparam = "gpid=123&gsh=TESTTOKEN";ASC.jscFieldsParams(gi42, ["datefrom","dateto","periodfrom","periodto","note","advanced_mode","remove_menu_evidence"]);gi42.ASC_action('ok', params);`;
const dialog = context.parseAbsenceNoteDialog(fixture);
assert.equal(dialog.gpid, '123');
assert.equal(context.parseAbsenceNoteDialog(fixture.replace('/gcall', 'https://other.example')), null);
assert.equal(context.parseAbsenceNoteDialog(fixture.replace('"note"', '"unknown"')), null);
assert.equal(profile(fixture).protocolRecognized, true);
const note = { date: '2026-09-17', first: 7, last: 9, reason: 'Kulturní akce & zkouška + č' };
const defaults = { advanced_mode: '', remove_menu_evidence: '0' };
const request = context.buildAbsenceNoteRequest(dialog, note, defaults);
assert.equal(new URLSearchParams(request.toString()).get('note'), note.reason);
assert.equal(request.get('action'), 'ok');
assert.equal(request.get('periodfrom'), '7');
assert.equal(request.get('periodto'), '9');
assert.throws(() => context.buildAbsenceNoteRequest(dialog, note, {}));
assert.throws(() => context.buildAbsenceNoteRequest(dialog, { ...note, date: '2026-02-30' }, defaults));
assert.throws(() => context.buildAbsenceNoteRequest(dialog, { ...note, first: 10 }, defaults));
assert.throws(() => context.buildAbsenceNoteRequest(dialog, { ...note, reason: '   ' }, defaults));
console.log('Adaptér: nové dialogy, odmítnutí změněného protokolu, UTF-8 a validace OK; bez síťového odeslání');
