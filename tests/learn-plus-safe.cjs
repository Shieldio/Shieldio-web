const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const page = read('learn/edupage/index.html');
const privacy = read('learn/edupage/soukromi/index.html');
const worker = read('learn/worker.js');
const config = read('wrangler.learn.jsonc');
const note = read('assets/js/plus-safe-note.js');

assert.match(page, /UKÁZKOVÁ DATA/);
assert.doesNotMatch(page, /name="(?:username|password|notePassword)"/);
assert.doesNotMatch(page, /data-edupage-probe|Potvrdit a odeslat/);
assert.doesNotMatch(page, /<form[\s>]/);
assert.match(page, /Do důvodu neuvádějte diagnózu/);
assert.match(page, /Otevřít EduPage/);
assert.doesNotMatch(note, /fetch\s*\(/);
assert.doesNotMatch(note, /localStorage|sessionStorage/);
assert.match(worker, /EDUPAGE_LOCAL_ENABLED/);
assert.match(worker, /integration-pending/);
assert.match(worker, /integration-pending[\s\S]*?503/);
assert.match(worker, /strict-transport-security/);
assert.match(worker, /frame-ancestors 'none'/);
assert.match(worker, /object-src 'none'/);
assert.match(worker, /cache-control.*no-store/);
assert.match(config, /"EDUPAGE_LOCAL_ENABLED": "false"/);
assert.match(privacy, /Integrace EduPage je dočasně deaktivována/);
assert.match(privacy, /Cloudflare zajišťuje hosting/);
assert.match(privacy, /shieldio-learn-theme/);
assert.match(privacy, /Úřadu pro ochranu osobních údajů/);
console.log('Learn+ je bezpečná ukázka: bez přihlášení, bez serverového odesílání, s lokálním návrhem a vypnutým API.');
