const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const source = fs.readFileSync('assets/js/pc-build-data.js', 'utf8');
const context = { window: {} };
vm.createContext(context);
vm.runInContext(source, context);
const data = context.window.PC_BUILD_DATA;
const total = items => items.reduce((sum, item) => sum + item.price, 0);
const pcTotal = total(data.pc);
const macTotal = data.mac.price + total(data.appleExtras);
assert.strictEqual(pcTotal, 28783);
assert.strictEqual(macTotal, 34748);
assert.ok(pcTotal <= data.limit, 'Windows sestava musí být pod limitem.');
assert.ok(data.pc.every(item => /^https:\/\/www\.alza\.cz\/.+-d\d+\.htm\?o=1$/.test(item.alzaUrl)), 'Každá PC položka má přímý detail Alzy.');
assert.ok(data.appleExtras.filter(item => item.alzaUrl).every(item => /^https:\/\/www\.alza\.cz\/.+-d\d+\.htm\?o=1$/.test(item.alzaUrl)), 'Příslušenství pro Mac musí mít přímý detail Alzy.');
assert.strictEqual(data.pc.find(item => item.id === 'cpu').specs[0], '6 jader / 12 vláken');
assert.match(data.pc.find(item => item.id === 'gpu').alzaUrl, /asus-dual-radeon-rx-7600-8g-oc-evo-d13104133/);
assert.strictEqual(data.pc.find(item => item.id === 'case').name, 'EVOLVEO Ursus Black');
assert.strictEqual(data.pc.find(item => item.id === 'speakers').name, 'Creative Pebble V3 · černé');
assert.match(data.pc.find(item => item.id === 'speakers').alzaUrl, /creative-pebble-v3-cerne-d7939616/);
assert.strictEqual(data.macBenefits.length, 4);
console.log('PC sestava: data, ceny a limity OK');
